// Integration with the running Hybrid service, a separate gateway and a disposable Mongo database.
const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const { spawn, spawnSync } = require('node:child_process');
const os = require('node:os');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const mongoose = require('mongoose');
const { setTimeout: delay } = require('node:timers/promises');

const dbName = 'chexnet_api_test_' + randomUUID().replaceAll('-', '');
const base = 'http://127.0.0.1:13006';
const logs = [];
let gateway;
let token;
let patient;
const storedFiles = [];
const fixtures = fs.mkdtempSync(path.join(os.tmpdir(), 'chexnet-api-dicom-'));

async function request(route, options = {}) {
    const response = await fetch(base + '/api/v1' + route, {
        ...options, headers: { Authorization: 'Bearer ' + token, ...options.headers },
    });
    return { status: response.status, body: await response.json() };
}

before(async () => {
    // Verify the chosen port is unused before starting this isolated process.
    let occupied = false;
    try { await fetch(base + '/health'); occupied = true; } catch {}
    assert.equal(occupied, false, 'Test gateway port is already in use');
    let aiReady = false;
    for (let attempt = 0; attempt < 120; attempt++) {
        try {
            const ai = await fetch('http://127.0.0.1:8000/health', { signal: AbortSignal.timeout(2000) }).then(r => r.json());
            aiReady = ai.status === 'healthy';
        } catch {}
        if (aiReady) break;
        await delay(500);
    }
    assert.ok(aiReady, 'Start the Hybrid AI service and wait for the model and validator');
    gateway = spawn(process.execPath, ['dist/server.js'], {
        cwd: path.resolve(__dirname, '..'),
        windowsHide: true,
        env: { ...process.env, PORT: '13006',
            MONGODB_URI: 'mongodb://127.0.0.1:27017/' + dbName,
            AI_SERVICE_URL: 'http://127.0.0.1:8000' },
        stdio: ['ignore', 'pipe', 'pipe'],
    });
    gateway.stdout.on('data', data => logs.push(data.toString()));
    gateway.stderr.on('data', data => logs.push(data.toString()));
    let ready = false;
    for (let attempt = 0; attempt < 60; attempt++) {
        if (gateway.exitCode !== null) throw new Error(logs.join(''));
        try { ready = (await fetch(base + '/health')).ok; } catch {}
        if (ready) break;
        await delay(500);
    }
    assert.ok(ready, logs.join(''));
    const login = await request('/auth/login', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ email: 'admin@chexnet.vn', password: 'Admin@123456' }),
    });
    assert.equal(login.status, 200);
    token = login.body.data.accessToken;
    const created = await request('/patients', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: 'API TEST Synthetic Patient', gender: 'Nam', age: 30 }),
    });
    assert.equal(created.status, 201);
    patient = created.body.data;
}, { timeout: 180000 });

after(async () => {
    if (gateway && gateway.exitCode === null) {
        const stopped = new Promise(resolve => gateway.once('exit', resolve));
        gateway.kill();
        await stopped;
    }
    await mongoose.connect('mongodb://127.0.0.1:27017/' + dbName);
    assert.equal(mongoose.connection.name, dbName);
    // Remove only the upload generated by this test, within the known upload directory.
    for (const storedFile of storedFiles) {
        const target = path.resolve(storedFile);
        const uploads = path.resolve(__dirname, '../private-uploads') + path.sep;
        assert.ok(target.startsWith(uploads) && path.basename(target).startsWith('scan_'));
        fs.rmSync(target, { force: true });
        fs.rmSync(target + '.preview.png', { force: true });
    }
    await mongoose.connection.dropDatabase();
    await mongoose.disconnect();
    fs.rmSync(fixtures, { recursive: true, force: true });
});

test('real gateway stores Hybrid result and replays upload without creating a scan', async () => {
    const key = randomUUID();
    const image = fs.readFileSync(path.resolve(__dirname, '../../Results/EX/Cardiomegally.png'));
    async function upload(bytes) {
        const form = new FormData();
        form.append('image', new Blob([bytes], { type: 'image/png' }), 'test.png');
        return request('/scans/' + patient._id + '/upload', {
            method: 'POST', body: form, headers: { 'Idempotency-Key': key },
        });
    }
    const first = await upload(image);
    assert.equal(first.status, 201, JSON.stringify(first.body));
    storedFiles.push(first.body.data.imagePath);
    const diagnosis = first.body.data.diagnosis;
    assert.equal(diagnosis.predictions.length, 15);
    assert.equal(diagnosis.inferenceMeta.contractVersion, 1);
    assert.equal(diagnosis.aiModel, 'hybrid-convnextv2-swinv2');
    const replay = await upload(image);
    assert.equal(replay.status, 200);
    assert.equal(replay.body.data._id, first.body.data._id);
    assert.deepEqual(replay.body.data.diagnosis.hybridAnalysis, diagnosis.hybridAnalysis);
    const conflict = await upload(Buffer.from('changed'));
    assert.equal(conflict.status, 409);
    const profile = await request('/patients/' + patient._id);
    assert.equal(profile.body.data.scans.length, 1);
    assert.equal(profile.body.data.diagnoses.length, 1);
    assert.deepEqual(profile.body.data.diagnoses[0].hybridAnalysis, diagnosis.hybridAnalysis);
    const preview = await fetch(base + first.body.data.imageUrl, {
        headers: { Authorization: 'Bearer ' + token },
    });
    assert.equal(preview.status, 200);
    assert.deepEqual(Buffer.from(await preview.arrayBuffer()), image);
    assert.equal((await fetch(base + first.body.data.imageUrl)).status, 401);
}, { timeout: 120000 });

test('DICOM passes through real Hybrid and its decoded preview survives a fresh profile read', async () => {
    const root = path.resolve(__dirname, '../..');
    const dicom = path.join(fixtures, 'synthetic-chest.dcm');
    const png = path.join(fixtures, 'expected.png');
    const generated = spawnSync(path.join(root, '.venv/Scripts/python.exe'), ['-c', [
        'import sys, pathlib, numpy as np',
        'from PIL import Image',
        'from Backend.tests.test_image_input import dicom_bytes',
        'from Backend.ai_service.image_input import decode_upload',
        'pixels = np.asarray(Image.open(sys.argv[1]).convert("L"), dtype=np.uint16)',
        'raw = dicom_bytes(pixels)',
        'pathlib.Path(sys.argv[2]).write_bytes(raw)',
        'pathlib.Path(sys.argv[3]).write_bytes(decode_upload(raw, "test.dcm")[1])',
    ].join('\n'), path.join(root, 'Results/EX/Cardiomegally.png'), dicom, png], {
        cwd: root, windowsHide: true, encoding: 'utf8',
    });
    assert.equal(generated.status, 0, generated.stderr);
    const form = new FormData();
    form.append('image', new Blob([fs.readFileSync(dicom)], { type: 'application/octet-stream' }), 'chest.dcm');
    const uploaded = await request('/scans/' + patient._id + '/upload', {
        method: 'POST', body: form, headers: { 'Idempotency-Key': randomUUID() },
    });
    assert.equal(uploaded.status, 201, JSON.stringify(uploaded.body));
    storedFiles.push(uploaded.body.data.imagePath);
    assert.equal(uploaded.body.data.diagnosis.predictions.length, 15);
    assert.ok(uploaded.body.data.previewPath.endsWith('.preview.png'));
    assert.equal(uploaded.body.data.diagnosis.previewPng, undefined);
    const profile = await request('/patients/' + patient._id);
    const scan = profile.body.data.scans.find(item => item._id === uploaded.body.data._id);
    const preview = await fetch(base + scan.imageUrl, { headers: { Authorization: 'Bearer ' + token } });
    assert.equal(preview.status, 200);
    assert.deepEqual(Buffer.from(await preview.arrayBuffer()), fs.readFileSync(png));
    assert.equal((await fetch(base + '/uploads/' + path.basename(scan.imagePath))).status, 404);
    assert.equal((await fetch(base + scan.imageUrl)).status, 401);
}, { timeout: 120000 });

test('saved doctor conclusions belong to their scan, reject stale edits and enforce role', async () => {
    const profile = await request('/patients/' + patient._id);
    const diagnoses = profile.body.data.diagnoses;
    assert.equal(diagnoses.length, 2);
    for (const [index, diagnosis] of diagnoses.entries()) {
        const result = await request('/diagnoses/' + diagnosis._id + '/verify', {
            method: 'PATCH', headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ status: index === 0 ? 'verified' : 'flagged',
                notes: 'Synthetic conclusion for scan ' + diagnosis.scanId, expectedRevision: 0 }),
        });
        assert.equal(result.status, 200, JSON.stringify(result.body));
        assert.equal(result.body.data.revision, 1);
        assert.ok(result.body.data.verifiedByName);
        const stale = await request('/diagnoses/' + diagnosis._id + '/verify', {
            method: 'PATCH', headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ status: 'flagged', notes: 'Stale edit', expectedRevision: 0 }),
        });
        assert.equal(stale.status, 409);
        const saved = await request('/diagnoses/' + diagnosis._id);
        assert.equal(saved.body.data.notes, 'Synthetic conclusion for scan ' + diagnosis.scanId);
        assert.deepEqual(saved.body.data.hybridAnalysis, diagnosis.hybridAnalysis);
        const pdf = await fetch(base + '/api/v1/diagnoses/' + diagnosis._id + '/report.pdf?revision=1', {
            headers: { Authorization: 'Bearer ' + token },
        });
        assert.equal(pdf.status, 200);
        assert.ok(pdf.headers.get('content-type').startsWith('application/pdf'));
        const pdfPath = path.join(fixtures, 'report-' + diagnosis._id + '.pdf');
        fs.writeFileSync(pdfPath, Buffer.from(await pdf.arrayBuffer()));
        const checked = spawnSync(path.resolve(__dirname, '../../.venv/Scripts/python.exe'), ['-c',
            'import sys,pymupdf; d=pymupdf.open(sys.argv[1]); t="".join(p.get_text() for p in d); assert sys.argv[2] in t; assert sys.argv[3] in t',
            pdfPath, String(diagnosis.scanId), 'Synthetic conclusion for scan ' + diagnosis.scanId],
        { windowsHide: true, encoding: 'utf8' });
        assert.equal(checked.status, 0, checked.stderr);
        const stalePdf = await request('/diagnoses/' + diagnosis._id + '/report.pdf?revision=0');
        assert.equal(stalePdf.status, 409);
    }
    const email = 'viewer-' + randomUUID() + '@example.com';
    const created = await request('/users', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: 'Disposable Viewer', email, password: 'Viewer@123456', role: 'user' }),
    });
    assert.equal(created.status, 201, JSON.stringify(created.body));
    const viewer = await request('/auth/login', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ email, password: 'Viewer@123456' }),
    });
    assert.equal(viewer.status, 200);
    const denied = await request('/diagnoses/' + diagnoses[0]._id + '/verify', {
        method: 'PATCH', headers: { 'Content-Type': 'application/json',
            Authorization: 'Bearer ' + viewer.body.data.accessToken },
        body: JSON.stringify({ status: 'verified', notes: 'Denied', expectedRevision: 1 }),
    });
    assert.equal(denied.status, 403);
});

test('AI health remains available through the gateway during real inference', async () => {
    const form = new FormData();
    form.append('image', new Blob([fs.readFileSync(path.resolve(__dirname, '../../Results/EX/Cardiomegally.png'))],
        { type: 'image/png' }), 'health-test.png');
    const upload = request('/scans/' + patient._id + '/upload', {
        method: 'POST', body: form, headers: { 'Idempotency-Key': randomUUID() },
    });
    let observedActive = false;
    for (let attempt = 0; attempt < 15; attempt++) {
        const health = await request('/system/ai-health');
        assert.equal(health.status, 200);
        if (health.body.data.inference.active === 1) { observedActive = true; break; }
        await delay(200);
    }
    const result = await upload;
    if (result.status === 201) storedFiles.push(result.body.data.imagePath);
    assert.equal(result.status, 201, JSON.stringify(result.body));
    assert.ok(observedActive, 'Health did not observe the active inference worker');
});
